"""Writes deploy/caddy/cloudflare-only.caddy (the origin guard) from CLOUDFLARE_IPS in monishield/domain/client_address.py,
the one list of Cloudflare ranges. Refresh after Cloudflare changes its ranges:

    python tools/cloudflare_ips.py --fetch     # downloads https://www.cloudflare.com/ips-v4 and ips-v6, rewrites both files
    python tools/cloudflare_ips.py             # only rewrites the Caddy snippet from the list in client_address.py

tests/test_cloudflare_guard.py fails when the two are out of step."""
import os, re, sys, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PY = os.path.join(ROOT, 'monishield', 'domain', 'client_address.py')
SNIPPET = os.path.join(ROOT, 'deploy', 'caddy', 'cloudflare-only.caddy')


def snippet(ranges):
    cidrs = [x.strip() for x in ranges.split(',') if x.strip()]
    return ('# Generated by tools/cloudflare_ips.py from CLOUDFLARE_IPS in monishield/domain/client_address.py. Do not edit.\n'
            '# Imported into the main site only when DOCKER_MAIN_CLOUDFLARE_ONLY=1: other addresses get no answer.\n'
            f'@not_cloudflare not remote_ip {" ".join(cidrs)}\n'
            'abort @not_cloudflare\n')


def python_literal(ranges):
    cidrs = [x.strip() for x in ranges.split(',') if x.strip()]
    lines, cur = [], ''
    for c in cidrs:
        if cur and len(cur) + len(c) > 100: lines.append(cur); cur = ''
        cur += c + ','
    lines.append(cur.rstrip(','))
    return 'CLOUDFLARE_IPS = (' + '\n                  '.join(f"'{x}'" for x in lines) + ')'


def fetch():
    out = []
    for v in ('ips-v4', 'ips-v6'):
        with urllib.request.urlopen(f'https://www.cloudflare.com/{v}', timeout=30) as r: out += r.read().decode().split()
    if len(out) < 10 or not all(re.fullmatch(r'[0-9a-fA-F:.]+/\d{1,3}', x) for x in out): sys.exit('unexpected answer from cloudflare.com/ips')
    return ','.join(out)


def main(argv):
    src = open(PY, encoding='utf-8').read()
    if '--fetch' in argv:
        src = re.sub(r'CLOUDFLARE_IPS = \(.*?\)\n', lambda m: python_literal(fetch()) + '\n', src, count=1, flags=re.S)
        open(PY, 'w', encoding='utf-8').write(src)
    ns = {}
    exec(re.search(r'CLOUDFLARE_IPS = \(.*?\)\n', src, re.S).group(0), ns)
    open(SNIPPET, 'w', encoding='utf-8').write(snippet(ns['CLOUDFLARE_IPS']))
    print('wrote', os.path.relpath(SNIPPET, ROOT))


if __name__ == '__main__': main(sys.argv[1:])
